static void bitpos(const unsigned char *p, size_t n, const char *name) {
    int first = -1, last = -1;
    for (size_t i = 0; i < n * 8; i++)
        if (p[i / 8] & (1u << (i % 8))) { if (first < 0) first = (int)i; last = (int)i; }
    printf("pub const %s: B = B(%d, %d, %d);\n", name, (first / 32) * 4, first % 32, last - first + 1);
}

#define SZ(T, NAME) printf("pub const %s: usize = %zu;\n", NAME, sizeof(T))
#define F(T, path, NAME) printf("pub const %s: F = F(%zu, %zu);\n", NAME, (size_t)offsetof(T, path), sizeof(((T *)0)->path))
#define B(T, path, NAME) do { static T x; memset(&x, 0, sizeof x); x.path = ~0u; bitpos((const unsigned char *)&x, sizeof x, NAME); } while (0)
#define V(expr, NAME) printf("pub const %s: u32 = 0x%08x;\n", NAME, (unsigned)(expr))
#define G(g, NAME) do { GUID v = g; printf("pub const %s: Guid = Guid { d1: 0x%08x, d2: 0x%04x, d3: 0x%04x, d4: [", NAME, v.Data1, v.Data2, v.Data3); \
    for (int i = 0; i < 8; i++) printf("0x%02x%s", v.Data4[i], i < 7 ? ", " : ""); printf("] };\n"); } while (0)

