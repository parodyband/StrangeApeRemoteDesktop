#!/usr/bin/env python3
"""Pre-render the Inter glyphs the viewer's status screen uses (connecting,
starting video, errors) into one grayscale atlas PNG plus a Rust metrics
table, so Sard can draw text without a font rasterizer at runtime.

    python3 tools/fontatlas/make_atlas.py <dir with Inter-Regular.ttf and Inter-SemiBold.ttf>

Writes crates/sard/assets/font/inter-atlas.png and crates/sard/src/font_atlas.rs.
Inter is under the SIL Open Font License 1.1 (assets/font/LICENSE-Inter.txt).
Needs Pillow.
"""
import os
import sys

from PIL import Image, ImageFont

SIZE = 48  # px per em; the screen scales glyphs down (and a little up) from here
PAD = 2  # empty pixels around each glyph so filtering never bleeds
ATLAS_W = 1024
CHARS = "".join(chr(c) for c in range(32, 127)) + "…—–·’‘“”•×"
WEIGHTS = [("Regular", "Inter-Regular.ttf"), ("SemiBold", "Inter-SemiBold.ttf")]

root = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", ".."))
src_dir = sys.argv[1] if len(sys.argv) > 1 else "."

glyphs = []  # (weight index, char, mask image, left, top, advance)
for wi, (_, fname) in enumerate(WEIGHTS):
    font = ImageFont.truetype(os.path.join(src_dir, fname), SIZE)
    for ch in CHARS:
        advance = font.getlength(ch)
        box = font.getbbox(ch, anchor="ls")  # relative to the baseline origin
        if box[2] <= box[0] or box[3] <= box[1]:
            glyphs.append((wi, ch, None, 0, 0, advance))
            continue
        img = Image.new("L", (box[2] - box[0], box[3] - box[1]), 0)
        from PIL import ImageDraw

        ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255, anchor="ls")
        glyphs.append((wi, ch, img, box[0], -box[1], advance))

# Shelf-pack, tallest first.
order = sorted(range(len(glyphs)), key=lambda i: -(glyphs[i][2].height if glyphs[i][2] else 0))
pos = {}
x = y = shelf = 0
for i in order:
    img = glyphs[i][2]
    if img is None:
        continue
    w, h = img.width + 2 * PAD, img.height + 2 * PAD
    if x + w > ATLAS_W:
        x, y, shelf = 0, y + shelf, 0
    pos[i] = (x + PAD, y + PAD)
    x += w
    shelf = max(shelf, h)
atlas_h = y + shelf
atlas = Image.new("L", (ATLAS_W, atlas_h), 0)
for i, (px, py) in pos.items():
    atlas.paste(glyphs[i][2], (px, py))
atlas.save(os.path.join(root, "crates/sard/assets/font/inter-atlas.png"), optimize=True)

out = [
    "// Generated by tools/fontatlas/make_atlas.py — do not edit.",
    "// Glyphs of Inter (SIL Open Font License 1.1, see assets/font/LICENSE-Inter.txt).",
    "",
    "use crate::status::Glyph;",
    "",
    f"/// Pixels per em the atlas was rendered at.\npub const SIZE: f32 = {SIZE}.0;",
    "",
    "/// Per weight (0 regular, 1 semibold), sorted by `ch`.",
    f"pub static GLYPHS: [&[Glyph]; {len(WEIGHTS)}] = [",
]
for wi in range(len(WEIGHTS)):
    out.append("    &[")
    rows = [(g[1], i) for i, g in enumerate(glyphs) if g[0] == wi]
    for ch, i in sorted(rows):
        _, _, img, left, top, adv = glyphs[i]
        gx, gy = pos.get(i, (0, 0))
        w, h = (img.width, img.height) if img else (0, 0)
        lit = repr(ch) if ch not in "\\'" else "'\\" + ch + "'"
        if ch == "'":
            lit = "'\\''"
        if ch == "\\":
            lit = "'\\\\'"
        out.append(
            f"        Glyph {{ ch: {lit}, x: {gx}, y: {gy}, w: {w}, h: {h}, left: {left}, top: {top}, advance: {adv:.3f} }},"
        )
    out.append("    ],")
out.append("];")
with open(os.path.join(root, "crates/sard/src/font_atlas.rs"), "w") as f:
    f.write("\n".join(out) + "\n")
print(f"atlas {ATLAS_W}x{atlas_h}, {len(glyphs)} glyphs")
