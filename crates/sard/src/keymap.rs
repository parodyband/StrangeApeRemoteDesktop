/// Swap Ctrl and Super/Cmd (used between macOS and Linux so that the
/// platform's "primary" modifier lines up: Cmd+C on a Mac → Ctrl+C on Linux).
pub fn swap_ctrl_meta(code: u16) -> u16 {
    match code {
        K::LEFTCTRL => K::LEFTMETA,
        K::LEFTMETA => K::LEFTCTRL,
        K::RIGHTCTRL => K::RIGHTMETA,
        K::RIGHTMETA => K::RIGHTCTRL,
        c => c,
    }
}
